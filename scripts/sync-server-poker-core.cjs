/* Keep server Hold'em and public-information bot estimates byte-identical to the tested local rules. */
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../dist/poker.html'), 'utf8');
const start = '// POKER_ENGINE_START', end = '// POKER_ENGINE_END';
if (source.split(start).length !== 2 || source.split(end).length !== 2) throw Error('Missing or duplicate poker engine markers');
const engine = source.split(start)[1].split(end)[0].trim();
const equity = fs.readFileSync(path.join(__dirname, '../dist/poker-equity.js'), 'utf8').trim();
const output = `// GENERATED by scripts/sync-server-poker-core.cjs. Do not hand-edit.\n// Canonical rules: dist/poker.html; public estimates: dist/poker-equity.js.\n// Both modules run in an isolated factory; no global state or random source is changed.\nexport function createCore({random}) {\nconst Math = Object.assign(Object.create(globalThis.Math), {random});\nconst module = {exports: {}};\n${equity}\nconst PokerEquity = module.exports;\n${engine}\nreturn {pokerNewGame, pokerDeal, pokerAction, pokerContinue, pokerNextHand, tableFinished, legalActions, botMove, pokerBotDecision, pokerBotEstimate, evaluate, splitPots};\n}\n`;
const target = path.join(__dirname, '../supabase/functions/server-poker/core.mjs');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw Error('Server poker rules are stale. Run node scripts/sync-server-poker-core.cjs');
} else {
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.writeFileSync(target, output);
}
