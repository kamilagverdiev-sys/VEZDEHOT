function declaration(kind,name){
  const match=new RegExp('^'+kind+' '+name+(kind==='function'?'\\(':'='),'m').exec(source);
  if(!match)throw Error('Missing shared Monopoly rule: '+name);
  const rest=source.slice(match.index),next=rest.slice(1).search(/\n(?:function |var |\/\/|<\/script>)/);
  return (next<0?rest:rest.slice(0,next+1)).trim();
}
